"""Independent check of the shipped icon textures against the generated table and the SBC.

"Independent" is the point: this does not import the builder, it re-reads the PNG files with
Pillow and re-parses the two generated artefacts. A bug in the builder that also produced a
matching artefact would be invisible to a self-check.

The icons are PNG, not DDS. The DDS version decoded correctly here and at every mip level and
still drew as an opaque square in the game's sprite path; PNG was the fix. ADR-0019 §1 records
the experiment table.

The catalogue previews in docs/icons/ are checked here too: they are generated by the same build
and referenced by docs/07-icon-catalog.md, so a preview that stopped being produced would leave
the catalogue pointing at a missing picture — which Markdown renders as a broken image, not as an
error.

Run: python tools/icon-atlas/verify_textures.py
"""

import os
import re
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TEXTURE_DIR = os.path.join(ROOT, r'src\GridWorkspace.Mod\Textures\VGS\Icons')
PREVIEW_DIR = os.path.join(ROOT, r'docs\icons')
CODE = os.path.join(ROOT, r'src\GridWorkspace.Mod\Data\Scripts\VGS\Ui\VgsIconAtlas.g.cs')
SBC = os.path.join(ROOT, r'src\GridWorkspace.Mod\Data\GuiTextures.sbc')

# The ink height, as a fraction of the texture side. Every glyph is scaled so that its ink fills
# the inset box *vertically* and is centred, so the ratio is the same for every icon:
# (256 - 2 * 8) / 256 = 0.9375. Height, not width: Font Awesome's viewBoxes differ in width (512,
# 448, 384 units at 512 tall), so the ink's width fraction differs per icon while the height is
# normalised by construction. Checking the width — which this check used to do, when all three
# icons happened to have square ink — would fail on the first tall icon added.
EXPECTED_INK_RATIO = 0.9375

# How far the ink's centre may sit from the texture's centre, as a fraction of the side. The build
# centres every glyph; a drift means the icon is drawn off-centre inside its own button.
INK_CENTRE_TOLERANCE = 0.01

# Side of a catalogue preview, in pixels (tools/icon-atlas/AtlasBuilder.cs, PreviewSize).
PREVIEW_SIZE = 96


def parse_table():
    text = open(CODE, encoding='utf-8').read()
    size = int(re.search(r'TextureSize = (\d+)', text).group(1))
    count = int(re.search(r'Count = (\d+)', text).group(1))
    names = re.findall(r'return "(VGS_\w+)";', text)
    scale = re.search(r'TextureScale\b.*?return ([0-9.]+)f', text, re.S)
    return size, count, names, scale.group(1) if scale else '?'


def parse_sbc():
    text = open(SBC, encoding='utf-8').read()
    return dict(re.findall(r'<SubtypeName>(VGS_\w+)</SubtypeName>\s*<Path>([^<]+)</Path>', text))


def ink_ratio(image):
    """Fraction of the side covered by the ink's bounding box *vertically*.

    The build normalises by ink height and centres the ink, so this is the one fraction that is
    the same for every icon regardless of how wide its viewBox is.
    """
    alpha = image.getchannel('A')
    box = alpha.getbbox()
    if box is None:
        return 0.0
    return (box[3] - box[1]) / float(image.size[1])


def ink_centre_offset(image):
    """Distance from the ink's centre to the texture's centre, as a fraction of the side."""
    alpha = image.getchannel('A')
    box = alpha.getbbox()
    if box is None:
        return 1.0
    side = float(image.size[0])
    centre_x = (box[0] + box[2]) * 0.5
    centre_y = (box[1] + box[3]) * 0.5
    return max(abs(centre_x - side * 0.5), abs(centre_y - side * 0.5)) / side


def main():
    size, count, names, texture_scale = parse_table()
    sbc = parse_sbc()

    problems = []
    print('table: %d icon(s), texture size %d, TextureScale %s' % (count, size, texture_scale))
    print()

    if len(names) != count:
        problems.append('table declares %d icon(s) but names %d' % (count, len(names)))

    for name in names:
        icon = name[4:] if name.startswith('VGS_') else name
        path = os.path.join(TEXTURE_DIR, icon + '.png')
        expected_path = 'Textures\\VGS\\Icons\\%s.png' % icon

        if name not in sbc:
            problems.append('%s is not registered in GuiTextures.sbc' % name)
            continue
        if sbc[name] != expected_path:
            problems.append('%s points at %s, expected %s' % (name, sbc[name], expected_path))
            continue
        if not os.path.exists(path):
            problems.append('%s is missing on disk' % path)
            continue

        image = Image.open(path)
        image.load()
        rgba = image.convert('RGBA')

        if image.size != (size, size):
            problems.append('%s is %dx%d, the table says %d' % (icon, image.size[0], image.size[1], size))

        # Straight alpha over white: every pixel's RGB must be 255, or the sprite shader would
        # multiply a tinted colour by alpha and darken the edges twice.
        r, g, b, a = rgba.split()
        if min(r.getextrema()) != 255 or min(g.getextrema()) != 255 or min(b.getextrema()) != 255:
            problems.append('%s has non-white RGB; alpha must be straight over white' % icon)

        if a.getextrema()[0] != 0:
            problems.append('%s has no fully transparent pixel; its corners must be clear' % icon)

        ratio = ink_ratio(rgba)
        if abs(ratio - EXPECTED_INK_RATIO) > 0.02:
            problems.append('%s ink is %.3f of the side tall, expected ~%.3f'
                            % (icon, ratio, EXPECTED_INK_RATIO))

        offset = ink_centre_offset(rgba)
        if offset > INK_CENTRE_TOLERANCE:
            problems.append('%s ink centre is off the texture centre by %.3f of the side'
                            % (icon, offset))

        # The catalogue preview: same icon, rasterised separately at the size a reader sees, on
        # the canvas colour. A missing or wrong-sized preview is a broken image in the catalogue.
        preview_path = os.path.join(PREVIEW_DIR, icon + '.png')
        if not os.path.exists(preview_path):
            problems.append('%s has no catalogue preview (docs/icons/%s.png)' % (icon, icon))
        else:
            preview = Image.open(preview_path)
            preview.load()
            if preview.size != (PREVIEW_SIZE, PREVIEW_SIZE):
                problems.append('docs/icons/%s.png is %dx%d, expected %dx%d'
                                % (icon, preview.size[0], preview.size[1],
                                   PREVIEW_SIZE, PREVIEW_SIZE))
            elif preview.convert('RGBA').getchannel('A').getextrema()[0] != 255:
                problems.append('docs/icons/%s.png is not opaque; the catalogue draws it on white'
                                % icon)

        status = 'OK'
        print('  %-16s %dx%d RGBA  ink %.3f of side  %s' % (icon, image.size[0], image.size[1], ratio, status))

    # A PNG nothing references is a file the mod ships for no reason.
    for file in os.listdir(TEXTURE_DIR):
        if not file.lower().endswith('.png'):
            continue
        name = 'VGS_' + os.path.splitext(file)[0]
        if name not in names:
            problems.append('%s is shipped but no icon references it' % file)

    # Same rule for the previews: one that no icon produced would show up in the catalogue as a
    # picture of something the mod does not draw.
    if os.path.isdir(PREVIEW_DIR):
        known = set(n[4:] + '.png' for n in names)
        for file in os.listdir(PREVIEW_DIR):
            if file.lower().endswith('.png') and file not in known:
                problems.append('docs/icons/%s has no matching icon' % file)

    # The DDS route was abandoned; a leftover would be shipped and never loaded.
    for file in os.listdir(TEXTURE_DIR):
        if file.lower().endswith('.dds'):
            problems.append('%s is a DDS, but the icons ship as PNG (ADR-0019 §1)' % file)

    print()
    if problems:
        print('TEXTURES FAILED — %d problem(s)' % len(problems))
        for problem in problems:
            print('  ' + problem)
        return 1

    print('TEXTURES OK — %d texture(s) agree with the generated table and the SBC' % len(names))
    return 0


if __name__ == '__main__':
    sys.exit(main())
